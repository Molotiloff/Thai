from datetime import date, datetime
from decimal import Decimal
from typing import Protocol

from domain.finance.models import PostedOperation
from services.finance.ports import FinanceUnitOfWork


class ClientsPort(Protocol):
    async def change_manager(self, telegram_user_id: int, display_name: str, enabled: bool) -> dict: ...
    async def wallet_adjustment_details(self, operation_id: int) -> dict: ...
    async def zero_preview(self, client_id: int) -> dict: ...

    async def lock_transfer(self, operation_id: int) -> None: ...
    async def transfer_context(self, operation_id: int) -> dict: ...

    async def lock_chat(self, chat_id: int) -> None: ...
    async def find_bootstrap(self, key: str) -> dict | None: ...
    async def save_bootstrap(self, key: str, fingerprint: str, telegram_user_id: int,
                             chat_id: int, client_id: int, name: str) -> None: ...
    async def ensure_chat_client(self, chat_id: int, name: str, *, preserve_name: bool = False) -> int: ...
    async def guard_directory(self, actor_id: int, key: str, permission: str = 'client.manage') -> None: ...
    async def find_event(self, key: str) -> dict | None: ...
    async def save_event(self, key: str, fingerprint: str, kind: str, actor_id: int,
                          payload: dict, result: dict) -> None: ...
    async def create_group(self, code: str, name: str) -> dict: ...
    async def rename_group(self, code: str, name: str) -> dict: ...
    async def create_client(self, name: str | None, party_id: int | None, group_code: str) -> dict: ...
    async def assign_group(self, client_id: int, group_code: str) -> dict: ...
    async def lock_client(self, client_id: int) -> dict: ...
    async def bind_chat(self, client_id: int, chat_id: int) -> dict: ...
    async def set_invite_link(self, client_id: int, invite_link: str | None) -> dict: ...
    async def close_client(self, client_id: int) -> dict: ...


class ClientUnitOfWork(FinanceUnitOfWork, Protocol):
    clients: ClientsPort


class WalletReadPort(Protocol):
    async def wallets(self, client_id: int) -> list[dict]: ...

    async def wallet_accounts(self, client_id: int, instrument: str) -> dict: ...

    async def adjustment_accounts(self, client_id: int, instrument: str) -> dict: ...


class LoanReadPort(Protocol):
    async def loans(self, *, client_id: int | None, after_client_id: int | None,
                    limit: int, include_zero: bool) -> list[dict]: ...
    async def loan_totals(self, client_id: int | None = None) -> dict: ...
    async def loan_wallet_history(self, client_id: int, instrument: str,
                                  before_id: int | None, limit: int) -> list[dict]: ...


class ClientTransferReadPort(WalletReadPort, Protocol):
    async def transfer_request(self, key: str) -> dict: ...
    async def transfer_context(self, operation_id: int) -> dict: ...
    async def transfer_recipients(self, name: str) -> list[dict]: ...
    async def transfer_by_message(self, chat_id: int, message_id: int) -> int | None: ...


class ClientTransferPostingPort(Protocol):
    async def transfer(self, *, key: str, actor_id: int, source_client_id: int, target_client_id: int,
                       instrument: str, quantity: Decimal | str, business_date: date,
                       effective_at: datetime, quoted_rate: Decimal | str | None = None,
                       comment: str = '', profit_revision_id: int | None = None,
                       work: FinanceUnitOfWork | None = None,
                       transfer_root_id: int | None = None) -> PostedOperation: ...


class WalletAuditReadPort(WalletReadPort, Protocol):
    async def wallet_history(self, client_id: int, instrument: str, before_id: int | None = None,
                             limit: int = 50) -> list[dict]: ...
    async def export_transactions(self, *, client_id: int, since: datetime | None = None,
                                  until: datetime | None = None) -> list[dict]: ...
    async def wallet_operation_by_message(self, chat_id: int, message_id: int) -> int | None: ...
    async def zero_preview(self, client_id: int) -> dict: ...
    async def directory_event(self, key: str) -> dict: ...
