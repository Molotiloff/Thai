from typing import Protocol

from services.clients.ports import ClientUnitOfWork


class ExpenseRepositoryPort(Protocol):
    async def guard(self, actor_id: int, permission: str) -> None: ...
    async def category(self, category_id: int) -> None: ...
    async def correction(self, expense_id: int) -> None: ...
    async def reversible(self, operation_id: int, day) -> None: ...
    async def debts(
        self, debtor: int, creditor: int, currency: str, day, obligation_ids=None
    ) -> list[dict]: ...
    async def save_expense(
        self, operation_id: int, command: dict, quote, shares, inputs, accounts
    ) -> int: ...
    async def save_resolution(
        self, operation_id: int, command: dict, allocations, quote
    ) -> int: ...
    async def prepare_close(self, period, revision_id) -> dict: ...
    async def save_close(self, operation_id: int, period, revision_id) -> int: ...
    async def start_revision(self, operation_id: int, period, reason: str) -> int: ...


class ExpenseUnitOfWork(ClientUnitOfWork, Protocol):
    expenses: ExpenseRepositoryPort


class ExpenseReadPort(Protocol):
    async def accounts(self, instrument: str, payer: str) -> dict: ...
    async def participant_wallet(self, client_id: int, debtor_id: int, instrument: str) -> dict: ...
    async def participant_client(self, code: str) -> int | None: ...
    async def posting_mode(self, key: str) -> str | None: ...
    async def preview_debts(
        self, debtor: int, creditor: int, currency: str, day, obligation_ids=None
    ) -> list[dict]: ...
    async def detail(self, expense_id: int) -> dict: ...
    async def resolution(self, resolution_id: int) -> dict: ...
