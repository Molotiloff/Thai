from datetime import date, datetime
from decimal import Decimal
from typing import Protocol

from domain.capital import CapitalLot, LotAllocation
from domain.finance.models import FxQuote
from services.finance.ports import FinanceUnitOfWork


class CapitalPort(Protocol):
    async def permission(self, actor_id: int, permission: str) -> None: ...
    async def lock_agreement(self, agreement_id: int, day: date | None = None) -> dict: ...
    async def create_agreement(self, operation_id: int, actor_id: int, day: date,
                               percent: Decimal, name: str | None, party_id: int | None) -> None: ...
    async def change_term(self, operation_id: int, agreement_id: int, actor_id: int,
                          valid_from: date, percent: Decimal) -> None: ...
    async def capital_day(self, agreement_id: int, day: date, effective_at: datetime) -> None: ...
    async def lots(self, agreement_id: int, instrument: str, day: date) -> tuple[CapitalLot, ...]: ...
    async def contribution(self, operation_id: int, agreement_id: int, instrument: str,
                           quantity: Decimal, principal: Decimal, comment: str) -> None: ...
    async def withdrawal(self, operation_id: int, agreement_id: int, instrument: str,
                         quantity: Decimal, allocations: tuple[LotAllocation, ...], comment: str) -> None: ...
    async def interest_basis(self, agreement_id: int, period: date) -> dict: ...
    async def accrue(self, operation_id: int, agreement_id: int, period: date,
                     basis: dict, calculated: Decimal, approved: Decimal, reason: str) -> None: ...
    async def unpaid(self, agreement_id: int, day: date) -> list[dict]: ...
    async def source_operations(self, agreement_id: int, before: date) -> list: ...
    async def pay(self, operation_id: int, agreement: dict, instrument: str, quantity: Decimal,
                   discharged: Decimal, allocations: list[tuple[int, int, Decimal]], reason: str,
                   *, quote: FxQuote, actor_id: int, effective_at) -> None: ...
    async def reversal_target(self, operation_id: int, agreement_id: int) -> None: ...


class CapitalUnitOfWork(FinanceUnitOfWork, Protocol):
    capital: CapitalPort


class CapitalReadPort(Protocol):
    async def accounts(self, agreement_id: int, instrument: str) -> dict: ...
