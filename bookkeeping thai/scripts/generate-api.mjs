import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const backend = new URL('../../CRM%C2%A0THB/', import.meta.url);
const python = process.env.THAI_API_PYTHON ?? fileURLToPath(new URL('.venv/bin/python', backend));
const schema = JSON.parse(execFileSync(python, ['-m', 'api.export_openapi'], {
  cwd: backend,
  encoding: 'utf8',
}));
const header = '// Generated by pnpm run generate:api from the Thai API factory.\n\n';
const generated = header + astToString(await openapiTS(schema));
const target = new URL('../src/api/openapi.ts', import.meta.url);

if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== generated) {
    console.error('Thai API types are stale. Run pnpm run generate:api.');
    process.exitCode = 1;
  }
} else {
  writeFileSync(target, generated);
}
